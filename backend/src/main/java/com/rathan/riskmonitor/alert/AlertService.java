package com.rathan.riskmonitor.alert;

import com.rathan.riskmonitor.audit.AuditAction;
import com.rathan.riskmonitor.audit.AuditService;
import com.rathan.riskmonitor.common.ConflictException;
import com.rathan.riskmonitor.common.ResourceNotFoundException;
import com.rathan.riskmonitor.transaction.Transaction;
import com.rathan.riskmonitor.user.Role;
import com.rathan.riskmonitor.user.User;
import com.rathan.riskmonitor.user.UserRepository;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.Pageable;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

@Service
public class AlertService {

    private final AlertRepository alertRepository;
    private final AuditService auditService;
    private final UserRepository userRepository;

    public AlertService(AlertRepository alertRepository, AuditService auditService, UserRepository userRepository) {
        this.alertRepository = alertRepository;
        this.auditService = auditService;
        this.userRepository = userRepository;
    }

    @Transactional
    public Alert createAlert(Transaction transaction, String ruleName, AlertSeverity severity, String reason) {
        Alert alert = new Alert(transaction, ruleName, severity, AlertStatus.OPEN, reason);
        Alert saved = alertRepository.save(alert);
        auditService.recordAction(saved, AuditAction.CREATED, "system", null, AlertStatus.OPEN.name(),
                "Alert generated by rule " + ruleName + ": " + reason);
        return saved;
    }

    @Transactional
    public Alert claimAlert(Long alertId, String username) {
        Alert alert = findAlertOrThrow(alertId);
        if (alert.getStatus() != AlertStatus.OPEN) {
            throw new ConflictException("Alert " + alertId + " is in status " + alert.getStatus() + " and cannot be claimed (must be OPEN)");
        }

        User user = findUserOrThrow(username);
        String oldStatus = alert.getStatus().name();
        alert.setStatus(AlertStatus.IN_REVIEW);
        alert.setAssignedTo(user);
        Alert updated = alertRepository.save(alert);

        auditService.recordAction(updated, AuditAction.CLAIMED, username, oldStatus, AlertStatus.IN_REVIEW.name(),
                "Claimed by " + username);
        return updated;
    }

    @Transactional
    public Alert escalateAlert(Long alertId, String username, String reason) {
        Alert alert = findAlertOrThrow(alertId);
        if (alert.getStatus() != AlertStatus.IN_REVIEW) {
            throw new ConflictException("Alert " + alertId + " is in status " + alert.getStatus() + " and cannot be escalated (must be IN_REVIEW)");
        }

        String oldStatus = alert.getStatus().name();
        alert.setStatus(AlertStatus.ESCALATED);
        alert.setReason(reason);
        Alert updated = alertRepository.save(alert);

        auditService.recordAction(updated, AuditAction.ESCALATED, username, oldStatus, AlertStatus.ESCALATED.name(),
                "Escalated by " + username + ": " + reason);
        return updated;
    }

    @Transactional
    public Alert closeAlert(Long alertId, String username, String outcome, String comment) {
        Alert alert = findAlertOrThrow(alertId);
        User user = findUserOrThrow(username);

        if (alert.getStatus() == AlertStatus.ESCALATED) {
            if (user.getRole() != Role.ROLE_MANAGER) {
                throw new AccessDeniedException("Only MANAGER role can close an ESCALATED alert");
            }
        } else if (alert.getStatus() != AlertStatus.IN_REVIEW) {
            throw new ConflictException("Alert " + alertId + " is in status " + alert.getStatus() + " and cannot be closed (must be IN_REVIEW or ESCALATED)");
        }

        AlertStatus targetStatus = "CONFIRMED".equalsIgnoreCase(outcome)
                ? AlertStatus.CLOSED_CONFIRMED
                : AlertStatus.CLOSED_FALSE_POSITIVE;

        String oldStatus = alert.getStatus().name();
        alert.setStatus(targetStatus);
        Alert updated = alertRepository.save(alert);

        String details = "Outcome: " + targetStatus.name() + (comment != null && !comment.isBlank() ? " | " + comment : "");
        auditService.recordAction(updated, AuditAction.CLOSED, username, oldStatus, targetStatus.name(), details);
        return updated;
    }

    @Transactional(readOnly = true)
    public Alert getAlert(Long alertId) {
        return findAlertOrThrow(alertId);
    }

    @Transactional(readOnly = true)
    public Page<Alert> listAlerts(AlertStatus status, AlertSeverity severity, String username, Pageable pageable) {
        User user = findUserOrThrow(username);
        if (user.getRole() == Role.ROLE_MANAGER) {
            return alertRepository.findAllFiltered(status, severity, pageable);
        } else {
            return alertRepository.findForAnalyst(status, severity, user.getId(), pageable);
        }
    }

    private Alert findAlertOrThrow(Long id) {
        return alertRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Alert not found with id: " + id));
    }

    private User findUserOrThrow(String username) {
        return userRepository.findByUsername(username)
                .orElseThrow(() -> new ResourceNotFoundException("User not found: " + username));
    }
}
